#!/usr/bin/env node
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { MOCKS, CATEGORIES } from '../src/index.js'

/**
 * The route inventory.
 *
 * Every endpoint every mock serves, in one file — so a reviewer can check
 * them against the provider's documentation without starting anything, and
 * so a change in an API shows up as a change in a list.
 *
 *   node scripts/routes.js          # print it
 *   node scripts/routes.js --write  # write docs/ROUTES.md
 */

const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** The path a route is written as. */
const describe = (route) => {
  if (typeof route.path === 'string') return route.path

  // A pattern written as a regular expression.
  return String(route.path.source)
    .replace(/^\^/, '')
    .replace(/\$$/, '')
    .replace(/\(\?<(\w+)>\[\^\/\]\+\)/g, ':$1')
    .replace(/\[\^\/\]\+/g, '*')
    .replace(/\\\//g, '/')
    .replace(/\\\./g, '.')
}

const lines = [
  '# The routes',
  '',
  'Every endpoint every mock serves.',
  '',
  'It is generated by `npm run routes`, so it cannot drift from the code.',
  'To check a route against the provider\'s own documentation, look it up',
  'there — and note that a mock serves the routes a test needs, not the',
  'whole API.',
  '',
]

for (const [category, title] of Object.entries(CATEGORIES)) {
  const names = Object.entries(MOCKS).filter(([, entry]) => entry.category === category)

  if (!names.length) continue

  lines.push(`## ${title.title}`, '')

  for (const [name] of names) {
    const service = MOCKS[name].create()

    lines.push(`### ${name}`, '')
    lines.push(`| Method | Path |`)
    lines.push(`|---|---|`)

    for (const route of service.routes) {
      const method = route.method === '*' ? 'ANY' : route.method

      lines.push(`| \`${method}\` | \`${describe(route)}\` |`)
    }

    lines.push('')
  }
}

const markdown = lines.join('\n')

if (process.argv.includes('--write')) {
  const target = join(ROOT, 'docs/ROUTES.md')

  await writeFile(target, markdown)

  console.log(`written: docs/ROUTES.md`)
} else {
  console.log(markdown)
}
